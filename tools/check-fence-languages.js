#!/usr/bin/env node
// Checks that every fenced code block this repository writes carries a
// language, and one from a fixed set.
//
// These flags are not only ours to read. The Markdown TypeDoc generates from
// these sources is rendered by the OpenINF portal, which highlights a block by
// its flag and holds its own pages to an allowlist of its own. A fence that
// names nothing reaches the portal as plain text, and one naming a language
// the portal does not know is one it cannot style.
//
// remark-lint-fenced-code-flag does this for Markdown, and the portal uses it.
// It is not enough here, because most of this repository's fences are not in
// Markdown at all: 89 of them sit inside JSDoc `@example` comments in
// TypeScript sources, where a Markdown linter cannot see them and where they
// nonetheless become fenced blocks on a published page.
//
// Run from the repo root: `pnpm run lint:fences`.

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');

/**
 * What a fence may say. Kept to what the portal's own allowlist accepts, so
 * that a block written here is one it can highlight. `ts` rather than
 * `typescript` and `bash` rather than `sh` are the spellings this project
 * settled on; the portal's list accepts both halves of that pair.
 */
const FLAGS = ['bash', 'console', 'diff', 'json', 'text', 'ts', 'yaml'];

/** A fence inside a JSDoc comment, which carries the comment's asterisk. */
const JSDOC_FENCE = /^\s*\*\s*```(\S*)\s*$/;

/** Generated by Changesets from the changeset files, which are checked. */
const GENERATED = new Set(['CHANGELOG.md']);

/**
 * Every file this repository writes a fence in: each package's README and its
 * sources, the changesets, and the Markdown at the root. Build output is not
 * among them -- a declaration file carries the same comment its source does,
 * and reporting it twice would name a path nobody can edit.
 */
function sources() {
  const found = [];

  const walk = (directory, extension) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const full = path.join(directory, entry.name);

      if (entry.isDirectory()) walk(full, extension);
      else if (entry.name.endsWith(extension)) found.push(full);
    }
  };

  for (const entry of fs.readdirSync(path.join(ROOT, 'packages'), {
    withFileTypes: true,
  })) {
    if (!entry.isDirectory()) continue;

    const readme = path.join(ROOT, 'packages', entry.name, 'README.md');
    if (fs.existsSync(readme)) found.push(readme);

    const src = path.join(ROOT, 'packages', entry.name, 'src');
    if (fs.existsSync(src)) walk(src, '.ts');
  }

  for (const entry of fs.readdirSync(path.join(ROOT, '.changeset'))) {
    if (entry.endsWith('.md')) found.push(path.join(ROOT, '.changeset', entry));
  }

  for (const entry of fs.readdirSync(ROOT)) {
    if (entry.endsWith('.md') && !GENERATED.has(entry)) {
      found.push(path.join(ROOT, entry));
    }
  }

  return found;
}

const problems = [];
let fences = 0;

/** Records one fence, or what is wrong with it. */
function check(file, line, flag) {
  fences += 1;
  const where = `${path.relative(ROOT, file)}:${line}`;

  if (flag === '') {
    problems.push(`${where}: fence has no language`);
  } else if (!FLAGS.includes(flag)) {
    problems.push(`${where}: \`${flag}\` is not one of ${FLAGS.join(', ')}`);
  }
}

for (const file of sources()) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  const markdown = file.endsWith('.md');
  let open = false;

  for (const [index, line] of lines.entries()) {
    if (markdown) {
      if (!line.startsWith('```')) continue;
      if (open) {
        open = false;
        continue;
      }
      open = true;
      check(file, index + 1, line.slice(3).trim());
      continue;
    }

    const found = line.match(JSDOC_FENCE);
    if (found === null) continue;
    if (open) {
      open = false;
      continue;
    }
    open = true;
    check(file, index + 1, found[1] ?? '');
  }
}

if (problems.length > 0) {
  console.error(
    `Fenced code blocks the portal could not highlight:\n\n${problems
      .map((problem) => `  ${problem}`)
      .join('\n')}\n`
  );
  process.exit(1);
}

if (fences === 0) {
  console.error('No fenced code blocks found, which cannot be right.');
  process.exit(1);
}

console.info(`Checked the language on ${fences} fenced code blocks.`);
